"""World events that charts can mark: wars, crises, treaties, pandemics, compiled by hand from Wikipedia.

Every chart on the site can show them (metric pages, Politics, Compare) as a line on its date.
A date is the day the event is usually dated to; a span (a war, a boom) also has its end, or none while it goes on.
The summary says, in one sentence, what happened and where the date is approximate.
"""

from dataclasses import dataclass
from datetime import date

from django.utils.translation import gettext_lazy as _

# Each kind has an icon and a colour in static/js/lib/events.js.
KINDS = {
    'conflict': _('Wars and attacks'),
    'treaty': _('Treaties and unions'),
    'economy': _('Economy'),
    'energy': _('Energy'),
    'politics': _('Politics'),
    'health': _('Health'),
    'disaster': _('Disasters'),
    'technology': _('Technology'),
}


@dataclass(frozen=True)
class WorldEvent:
    slug: str
    date: date
    kind: str
    title: str  # short: it sits on the chart
    summary: str
    wiki: str
    end: date | None = None  # a span's last day; None while it goes on
    ongoing: bool = False  # a span without an end yet

    def as_json(self):
        return {
            'slug': self.slug,
            'date': self.date.isoformat(),
            'end': self.end.isoformat() if self.end else None,
            'ongoing': self.ongoing,
            'kind': self.kind,
            'kindLabel': str(KINDS[self.kind]),
            'title': str(self.title),
            'summary': str(self.summary),
            'wiki': self.wiki,
        }


def _wiki(article):
    return f'https://en.wikipedia.org/wiki/{article}'


